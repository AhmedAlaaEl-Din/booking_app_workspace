import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';
import 'package:material_ui/material_ui.dart';

import 'app.dart';
import 'features/bookings/data/booking_reminders.dart';
import 'firebase_options.dart'; // Generated by `flutterfire configure`.

/// Debug-only switch: `flutter run --dart-define=USE_EMULATOR=true` talks to
/// the local Firebase Emulator Suite instead of the real project. On a USB
/// phone, first run `adb reverse tcp:8080 tcp:8080` and `adb reverse tcp:9099
/// tcp:9099`. Release and profile builds ignore it ([kDebugMode] is false).
const bool _useEmulatorFlag = bool.fromEnvironment('USE_EMULATOR');
const String _emulatorHost = String.fromEnvironment(
  'EMULATOR_HOST',
  defaultValue: '127.0.0.1',
);
const bool useEmulator = kDebugMode && _useEmulatorFlag;

Future<void> main() async {
  // Required before using plugins (like Firebase) ahead of runApp().
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  if (useEmulator) await _connectToEmulators();

  final reminders = BookingReminders();
  try {
    await reminders.init();
  } catch (error) {
    // Reminders are a nice-to-have: the app must still start without them.
    debugPrint('Reminders unavailable: $error');
  }

  runApp(BookingApp(reminders: reminders));
}

/// Must run before anything else uses Auth or Firestore.
Future<void> _connectToEmulators() async {
  debugPrint('Using the Firebase emulators on $_emulatorHost (debug only).');
  await FirebaseAuth.instance.useAuthEmulator(_emulatorHost, 9099);
  FirebaseFirestore.instance.useFirestoreEmulator(_emulatorHost, 8080);
  // No offline cache: it could hold data from the real project.
  FirebaseFirestore.instance.settings = const Settings(
    persistenceEnabled: false,
  );
  // A session saved from the real project must not carry over.
  await FirebaseAuth.instance.signOut();
}
